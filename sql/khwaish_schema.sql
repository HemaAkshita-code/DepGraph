-- 1. YOUR TABLES
CREATE TABLE vulnerabilities (
    vuln_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advisory_code  VARCHAR2(40)  NOT NULL UNIQUE,
    title          VARCHAR2(200) NOT NULL,
    severity_score NUMBER(3,1) CHECK (severity_score BETWEEN 0 AND 10),
    published_on   DATE
);

CREATE TABLE affected_versions (
    affected_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vuln_id     NUMBER NOT NULL,
    package_id  NUMBER NOT NULL,
    min_major   NUMBER(5) NOT NULL,
    min_minor   NUMBER(5) DEFAULT 0 NOT NULL,
    min_patch   NUMBER(5) DEFAULT 0 NOT NULL,
    max_major   NUMBER(5) NOT NULL,
    max_minor   NUMBER(5) DEFAULT 0 NOT NULL,
    max_patch   NUMBER(5) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_aff_vuln FOREIGN KEY (vuln_id) REFERENCES vulnerabilities(vuln_id),
    CONSTRAINT fk_aff_pkg FOREIGN KEY (package_id) REFERENCES packages(package_id)
);

CREATE TABLE project_exposures (
    exposure_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id      NUMBER NOT NULL,
    vuln_id         NUMBER NOT NULL,
    version_id      NUMBER NOT NULL,
    root_version_id NUMBER NOT NULL,
    depth           NUMBER NOT NULL,
    path_text       VARCHAR2(4000),
    detected_at     DATE DEFAULT SYSDATE,
    CONSTRAINT fk_exp_project FOREIGN KEY (project_id) REFERENCES projects(project_id),
    CONSTRAINT fk_exp_vuln FOREIGN KEY (vuln_id) REFERENCES vulnerabilities(vuln_id),
    CONSTRAINT fk_exp_version FOREIGN KEY (version_id) REFERENCES package_versions(version_id)
);

