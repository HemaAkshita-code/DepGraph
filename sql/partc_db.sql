-- ==========================================================
-- 1. REMEDIATION_POLICIES TABLE
-- ==========================================================
CREATE TABLE remediation_policies (
    policy_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority       VARCHAR2(20) NOT NULL 
                   CONSTRAINT chk_policy_priority CHECK (priority IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    deadline_hours NUMBER NOT NULL,
    policy_version NUMBER NOT NULL,
    is_active      CHAR(1) DEFAULT 'Y' NOT NULL 
                   CONSTRAINT chk_policy_is_active CHECK (is_active IN ('Y', 'N')),
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    -- Unique constraint on priority and policy version
    CONSTRAINT uk_priority_version UNIQUE (priority, policy_version)
);

-- Unique index trick to allow at most one active policy per priority 
-- (Zero active policies are allowed because NULL columns are ignored in Oracle unique indexes)
CREATE UNIQUE INDEX ux_one_active_policy_per_priority 
ON remediation_policies (CASE WHEN is_active = 'Y' THEN priority ELSE NULL END);


-- ==========================================================
-- 2. FIX_TASKS TABLE
-- ==========================================================
CREATE TABLE fix_tasks (
    task_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        NUMBER NOT NULL, -- Assumes a 'projects' table exists
    vuln_id           NUMBER NOT NULL, -- Assumes a 'vulnerabilities' table exists
    team_id           NUMBER,          -- Nullable; FK to 'teams' table
    assigned_to       NUMBER,          -- Nullable; FK to 'users' table (developer)
    reviewer_user_id  NUMBER,          -- Nullable; FK to 'users' table
    created_by        NUMBER NOT NULL, -- FK to 'users' table
    policy_id         NUMBER NOT NULL, -- FK to 'remediation_policies' table
    status            VARCHAR2(30) NOT NULL 
                      CONSTRAINT chk_task_status CHECK (status IN (
                          'OPEN', 'IN_PROGRESS', 'IN_VERIFICATION', 
                          'IN_REVIEW', 'CHANGES_REQUESTED', 'RESOLVED', 'CANCELLED'
                      )),
    due_at            TIMESTAMP NOT NULL,
    priority_reason   VARCHAR2(500),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    closed_at         TIMESTAMP,       -- Nullable
    -- Foreign Key constraints (assuming parent tables exist)
    CONSTRAINT fk_task_project FOREIGN KEY (project_id) REFERENCES projects(project_id),
    CONSTRAINT fk_task_vuln FOREIGN KEY (vuln_id) REFERENCES vulnerabilities(vuln_id),
    CONSTRAINT fk_task_team FOREIGN KEY (team_id) REFERENCES teams(team_id),
    CONSTRAINT fk_task_assigned FOREIGN KEY (assigned_to) REFERENCES users(user_id),
    CONSTRAINT fk_task_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_task_creator FOREIGN KEY (created_by) REFERENCES users(user_id),
    CONSTRAINT fk_task_policy FOREIGN KEY (policy_id) REFERENCES remediation_policies(policy_id)
);

-- ==========================================================
-- 1. FIX_SUBMISSIONS TABLE
-- ==========================================================
CREATE TABLE fix_submissions (
    submission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- PK[cite: 3]
    task_id         NUMBER NOT NULL,                                     -- FK -> fix_tasks[cite: 3]
    submitted_by    NUMBER NOT NULL,                                     -- FK -> users (from session)[cite: 3]
    commit_sha      VARCHAR2(40) NOT NULL,                               -- Exact code version[cite: 3]
    base_sha        VARCHAR2(40) NOT NULL,                               -- Code before the fix[cite: 3]
    pull_request_url VARCHAR2(500),                                      -- Pull request URL[cite: 3]
    change_summary  VARCHAR2(1000),                                      -- Change summary[cite: 3]
    submitted_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,             -- Timestamp of submission[cite: 3]
    -- Foreign Key constraints (assuming parent tables exist)
    CONSTRAINT fk_sub_task FOREIGN KEY (task_id) REFERENCES fix_tasks(task_id),
    CONSTRAINT fk_sub_user FOREIGN KEY (submitted_by) REFERENCES users(user_id)
);


-- ==========================================================
-- 2. FIX_REVIEWS TABLE
-- ==========================================================
CREATE TABLE fix_reviews (
    review_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- PK
    submission_id   NUMBER NOT NULL,                                     -- FK -> fix_submissions
    reviewer_user_id NUMBER NOT NULL,                                    -- FK -> users[cite: 4]
    decision        VARCHAR2(30) NOT NULL                                -- CHECK in (APPROVED, CHANGES_REQUESTED)[cite: 4]
                    CONSTRAINT chk_review_decision CHECK (decision IN ('APPROVED', 'CHANGES_REQUESTED')),
    feedback        VARCHAR2(1000),                                      -- Feedback (required when CHANGES_REQUESTED)[cite: 4]
    reviewed_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,             -- Timestamp of review[cite: 4]
    -- Check constraint to ensure feedback is provided when changes are requested
    CONSTRAINT chk_feedback_required CHECK (
        (decision = 'APPROVED') OR 
        (decision = 'CHANGES_REQUESTED' AND feedback IS NOT NULL)
    ),
    -- Foreign Key constraints (assuming parent tables exist)
    CONSTRAINT fk_rev_submission FOREIGN KEY (submission_id) REFERENCES fix_submissions(submission_id),
    CONSTRAINT fk_rev_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users(user_id)
);

-- ==========================================================
-- 1. HISTORY_LOG TABLE
-- ==========================================================
CREATE TABLE history_log (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- PK
    task_id       NUMBER NOT NULL,                                     -- FK -> fix_tasks[cite: 5]
    actor_user_id NUMBER,                                              -- FK -> users, nullable (NULL = system action)[cite: 5]
    action        VARCHAR2(50) NOT NULL,                               -- Action performed (e.g., TASK_CREATED, TEAM_ASSIGNED, etc.)[cite: 5]
    old_values    CLOB,                                                -- JSON with changed fields[cite: 5]
    new_values    CLOB,                                                -- JSON with changed fields[cite: 5]
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,             -- Timestamp of log entry[cite: 5]
    -- IS JSON check constraints for Oracle CLOB/VARCHAR2 JSON columns
    CONSTRAINT chk_history_old_json CHECK (old_values IS JSON),
    CONSTRAINT chk_history_new_json CHECK (new_values IS JSON),
    -- Foreign Key constraints (assuming parent tables exist)
    CONSTRAINT fk_history_task FOREIGN KEY (task_id) REFERENCES fix_tasks(task_id),
    CONSTRAINT fk_history_actor FOREIGN KEY (actor_user_id) REFERENCES users(user_id)
);


