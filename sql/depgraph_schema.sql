-- DepGraph schema (Oracle)

CREATE TABLE users (
    user_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    VARCHAR2(100) NOT NULL,
    email        VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255),
    must_change_password CHAR(1) DEFAULT 'Y' NOT NULL CHECK (must_change_password IN ('Y','N')),
    system_role  VARCHAR2(20)  NOT NULL
                 CHECK (system_role IN ('ADMIN','SECURITY_ANALYST','DEVELOPER','AUDITOR')),
    designation  VARCHAR2(30)  NOT NULL
                 CHECK (designation IN ('SENIOR_DEVELOPER','DEVELOPER','INTERN',
                                        'SECURITY_ENGINEER','AUDITOR','MANAGER')),
    is_active    CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y','N')),
    joined_on    DATE    DEFAULT SYSDATE NOT NULL,
    left_on      DATE,
    CONSTRAINT chk_user_dates CHECK (left_on IS NULL OR left_on >= joined_on)
);

CREATE TABLE user_sessions (
    session_token VARCHAR2(64) PRIMARY KEY,
    user_id       NUMBER NOT NULL,
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    expires_at    DATE NOT NULL,
    CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_session_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_sessions_user ON user_sessions(user_id);

CREATE TABLE teams (
    team_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_name      VARCHAR2(100) NOT NULL UNIQUE,
    leader_user_id NUMBER,
    created_on     DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE team_members (
    team_id    NUMBER NOT NULL,
    user_id    NUMBER NOT NULL,
    team_role  VARCHAR2(20) DEFAULT 'DEVELOPER' NOT NULL
               CHECK (team_role IN ('DEVELOPER','REVIEWER','TESTER')),
    joined_on  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_team_members PRIMARY KEY (team_id, user_id),
    CONSTRAINT fk_tm_team FOREIGN KEY (team_id) REFERENCES teams(team_id) ON DELETE CASCADE,
    CONSTRAINT fk_tm_user FOREIGN KEY (user_id) REFERENCES users(user_id)
);

ALTER TABLE teams ADD CONSTRAINT fk_team_leader
    FOREIGN KEY (team_id, leader_user_id) REFERENCES team_members(team_id, user_id);

CREATE TABLE projects (
    project_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name  VARCHAR2(100) NOT NULL UNIQUE,
    description   VARCHAR2(500),
    repo_url      VARCHAR2(300) UNIQUE CHECK (repo_url LIKE 'https://%'),
    scanned_commit_sha VARCHAR2(40) CHECK (LENGTH(scanned_commit_sha) = 40),
    scanned_at    DATE,
    owner_team_id NUMBER NOT NULL,
    created_by    NUMBER NOT NULL,
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_proj_team FOREIGN KEY (owner_team_id) REFERENCES teams(team_id),
    CONSTRAINT fk_proj_user FOREIGN KEY (created_by)    REFERENCES users(user_id)
);

CREATE TABLE packages (
    package_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name VARCHAR2(100) NOT NULL,
    ecosystem    VARCHAR2(20) DEFAULT 'PyPI' NOT NULL CHECK (ecosystem IN ('PyPI')),
    license      VARCHAR2(50),
    CONSTRAINT uq_package UNIQUE (ecosystem, package_name)
);

CREATE TABLE package_versions (
    version_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id  NUMBER NOT NULL,
    major_no    NUMBER(5) NOT NULL           CHECK (major_no >= 0),
    minor_no    NUMBER(5) DEFAULT 0 NOT NULL CHECK (minor_no >= 0),
    patch_no    NUMBER(5) DEFAULT 0 NOT NULL CHECK (patch_no >= 0),
    released_on DATE,
    CONSTRAINT fk_pv_package FOREIGN KEY (package_id)
        REFERENCES packages(package_id) ON DELETE CASCADE,
    CONSTRAINT uq_version UNIQUE (package_id, major_no, minor_no, patch_no)
);

CREATE TABLE dependencies (
    dep_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NUMBER NOT NULL,
    version_id NUMBER NOT NULL,
    added_at   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_dep_project FOREIGN KEY (project_id)
        REFERENCES projects(project_id) ON DELETE CASCADE,
    CONSTRAINT fk_dep_version FOREIGN KEY (version_id)
        REFERENCES package_versions(version_id),
    CONSTRAINT uq_project_version UNIQUE (project_id, version_id)
);

CREATE TABLE package_deps (
    parent_version_id NUMBER NOT NULL,
    child_version_id  NUMBER NOT NULL,
    CONSTRAINT pk_package_deps PRIMARY KEY (parent_version_id, child_version_id),
    CONSTRAINT fk_pdeps_parent FOREIGN KEY (parent_version_id)
        REFERENCES package_versions(version_id) ON DELETE CASCADE,
    CONSTRAINT fk_pdeps_child  FOREIGN KEY (child_version_id)
        REFERENCES package_versions(version_id),
    CONSTRAINT chk_no_self_dep CHECK (parent_version_id <> child_version_id)
);

CREATE INDEX idx_pdeps_child ON package_deps(child_version_id);

CREATE OR REPLACE VIEW project_all_dependencies AS
WITH dep_tree (project_id, root_version_id, version_id, depth, path_text) AS (
    SELECT d.project_id,
           d.version_id,
           d.version_id,
           1,
           CAST(p.package_name || ' ' || pv.major_no || '.' || pv.minor_no || '.' || pv.patch_no
                AS VARCHAR2(4000))
    FROM dependencies d
    JOIN package_versions pv ON pv.version_id = d.version_id
    JOIN packages p ON p.package_id = pv.package_id

    UNION ALL

    SELECT t.project_id,
           t.root_version_id,
           pd.child_version_id,
           t.depth + 1,
           t.path_text || ' > ' || p.package_name || ' '
               || pv.major_no || '.' || pv.minor_no || '.' || pv.patch_no
    FROM dep_tree t
    JOIN package_deps pd ON pd.parent_version_id = t.version_id
    JOIN package_versions pv ON pv.version_id = pd.child_version_id
    JOIN packages p ON p.package_id = pv.package_id
    WHERE t.depth < 20
)
CYCLE version_id SET is_cycle TO 'Y' DEFAULT 'N'
SELECT t.project_id,
       t.root_version_id,
       rp.package_name AS root_package_name,
       t.version_id,
       pv.package_id,
       p.package_name,
       pv.major_no || '.' || pv.minor_no || '.' || pv.patch_no AS version_text,
       t.depth,
       t.path_text
FROM dep_tree t
JOIN package_versions pv  ON pv.version_id  = t.version_id
JOIN packages p           ON p.package_id   = pv.package_id
JOIN package_versions rpv ON rpv.version_id = t.root_version_id
JOIN packages rp          ON rp.package_id  = rpv.package_id
WHERE t.is_cycle = 'N';

